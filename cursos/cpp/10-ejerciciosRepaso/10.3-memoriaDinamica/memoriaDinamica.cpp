#include <iostream>
using namespace std;
// =============================================================================
//  Clase Cofre
// =============================================================================
class Cofre
{
    public:
        //  Métodos
        void abrir()
        {
            cout << "¡Cofre abierto!\n";
        }
};
// =============================================================================
//  main()
// =============================================================================
int main()
{
    Cofre *objeto = new Cofre;
    objeto->abrir();

    delete objeto;
    objeto = nullptr;

    return 0;
}
