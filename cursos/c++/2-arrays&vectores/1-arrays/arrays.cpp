/*
-------------------------------------------------------------------------------------------------------
Arrays
-------------------------------------------------------------------------------------------------------

- Es una estructura de datos que contiene una colección de valores del mismo tipo.

- Sirven para almacenar valores que normalmente tienen alguna relación entre sí.

- Su sintaxis es: "tipo de datos guardados" "nombre de la matriz"["nº de valores"]

-------------------------------------------------------------------------------------------------------
Declaración e inicialización:

- "Tipo" "nombre"["nº de elementos"]{"elementos"}; => Esto crea un array almacenando valores
en el mismo orden que hemos declarado los elementos del array.

- "tipo" "nombre"["nº de elementos"]{"menos elementos del nº de elementos"}; => Hará que todos los
valores no declarados sean 0.

- "const int" "nombre de la constante" = "nº de elementos";
"tipo" "nombre del arreglo"["nombre de la constante"]{"elementos"}; =>

Esto declara un array con un tamaño fijo dado por la constante.

- "tipo" "nombre" []{"elementos"}; => Genera un arreglo con los elementos dentro de él.
-------------------------------------------------------------------------------------------------------
Como acceder o almacenar valores dentro de un array:

- Almacenar => "nombre del arreglo"["índice donde se guardará el valor"] = "valor deseado";

- Acceder o modificar => "nombre del arreglo"["índice del arreglo"];
-------------------------------------------------------------------------------------------------------
*/
