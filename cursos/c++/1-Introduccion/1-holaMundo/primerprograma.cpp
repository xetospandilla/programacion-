#include <iostream> //Introduce una biblioteca y permite el acceso a su contenido.
using namespace std; //Permite usar nombres de std, como cout y endl, sin escribir "std::".

//-----------------------------------------------------------------------------------------------------

int main (){ //Abre la función principal del programa. "Main" es una función tipo entera en este caso.
    
    cout << "Hola, que tal?" << endl;
    /* 
    cout -> Indica que lo posterior se imprimirá en consola.
    En este caso en específico el string "Hola, que tal?" será lo que se imprimirá en consola.
    endl -> Indica el final de una salida con un salto de línea respecto al siguiente texto.
    */
    return 0; 
    /* 
    return -> nos devuelve un valor.
    Normalmente suele ser el resultado de los cálculos o lo que queremos que nos devuelva una función.
    
    En este caso es el literal entero 0.
    */
}
